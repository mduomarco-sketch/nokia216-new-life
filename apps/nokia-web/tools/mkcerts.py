#!/usr/bin/env python3
"""Generate src/certificates.h (BearSSL trust anchors) from Mozilla's CA list (certifi).

Picks a small set of roots that cover most of the web; the phone has little
flash/RAM, so shipping the whole bundle is not an option.
"""
import sys
import certifi
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

WANTED = [
    "ISRG Root X1", "ISRG Root X2",                                  # Let's Encrypt
    "DigiCert Global Root CA", "DigiCert Global Root G2", "DigiCert Global Root G3",
    "DigiCert High Assurance EV Root CA", "DigiCert TLS RSA4096 Root G5",
    "GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4",      # Google / Cloudflare
    "GlobalSign Root CA", "GlobalSign",                              # R1, R3/R6 share the CN
    "Amazon Root CA 1", "Amazon Root CA 2", "Amazon Root CA 3", "Amazon Root CA 4",
    "USERTrust RSA Certification Authority", "USERTrust ECC Certification Authority",  # Sectigo
    "Go Daddy Root Certificate Authority - G2", "Starfield Root Certificate Authority - G2",
    "Microsoft RSA Root Certificate Authority 2017", "Microsoft ECC Root Certificate Authority 2017",
    "SSL.com Root Certification Authority RSA", "SSL.com Root Certification Authority ECC",
    "Certum Trusted Network CA", "HARICA TLS RSA Root CA 2021",
]
CURVES = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}


def carray(name, data):
    lines = [", ".join(f"0x{b:02X}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"static const unsigned char {name}[] = {{\n\t" + ",\n\t".join(lines) + "\n};\n"


def main(out_path):
    pem = open(certifi.where(), "rb").read()
    certs = x509.load_pem_x509_certificates(pem)
    picked = []
    for cert in certs:
        cn = cert.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
        cn = cn[0].value if cn else ""
        if cn in WANTED:
            picked.append((cn, cert))
    found = {cn for cn, _ in picked}
    for cn in WANTED:
        if cn not in found:
            print("missing:", cn, file=sys.stderr)

    out = ["/* Generated by tools/mkcerts.py from certifi (Mozilla CA list). Do not edit. */",
           "#pragma once", '#include "bearssl.h"', ""]
    anchors = []
    for i, (cn, cert) in enumerate(picked):
        out.append(f"/* {cn} | {cert.subject.rfc4514_string()} */")
        out.append(carray(f"TA{i}_DN", cert.subject.public_bytes()))
        key = cert.public_key()
        if isinstance(key, rsa.RSAPublicKey):
            n = key.public_numbers()
            nb = n.n.to_bytes((n.n.bit_length() + 7) // 8, "big")
            eb = n.e.to_bytes((n.e.bit_length() + 7) // 8, "big")
            out.append(carray(f"TA{i}_RSA_N", nb))
            out.append(carray(f"TA{i}_RSA_E", eb))
            anchors.append(f"\t{{ {{ (unsigned char *)TA{i}_DN, sizeof TA{i}_DN }}, BR_X509_TA_CA,\n"
                           f"\t  {{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *)TA{i}_RSA_N, sizeof TA{i}_RSA_N,"
                           f" (unsigned char *)TA{i}_RSA_E, sizeof TA{i}_RSA_E }} }} }} }}")
        elif isinstance(key, ec.EllipticCurvePublicKey):
            curve = CURVES[key.curve.name]
            q = key.public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
            out.append(carray(f"TA{i}_EC_Q", q))
            anchors.append(f"\t{{ {{ (unsigned char *)TA{i}_DN, sizeof TA{i}_DN }}, BR_X509_TA_CA,\n"
                           f"\t  {{ BR_KEYTYPE_EC, {{ .ec = {{ {curve}, (unsigned char *)TA{i}_EC_Q, sizeof TA{i}_EC_Q }} }} }} }}")
    out.append(f"#define TAs_NUM {len(anchors)}")
    out.append("static const br_x509_trust_anchor TAs[TAs_NUM] = {\n" + ",\n".join(anchors) + "\n};")
    open(out_path, "w", newline="\n").write("\n".join(out) + "\n")
    print(f"wrote {len(anchors)} trust anchors to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/certificates.h")
